"""
Pydantic Schemas for Hidani AI Job Assistant.
Defines data structures for resumes, jobs, applications, and chat interactions.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ResumeData(BaseModel):
    """Structured representation of extracted candidate resume data matching assessment criteria."""
    name: str = Field(default="Candidate", description="Applicant full name")
    contact: str = Field(default="", description="Email and phone contact information")
    email: Optional[str] = Field(default=None, description="Contact email address")
    phone: Optional[str] = Field(default=None, description="Contact phone number")
    designation: str = Field(default="Software Engineer", description="Current or target professional designation/title")
    skills: List[str] = Field(default_factory=list, description="Technical and domain skills")
    experience: str = Field(default="1-3 years", description="Total experience and background summary")
    experience_years: Optional[str] = Field(default="1-3 years", description="Years of total experience")
    experience_level: Optional[str] = Field(default="Mid-Level", description="Entry-Level, Mid-Level, Senior, or Lead")
    education: List[str] = Field(default_factory=list, description="Academic degrees, university, graduation year")
    projects: List[str] = Field(default_factory=list, description="Key projects worked on with brief tech stack")
    preferred_roles: List[str] = Field(default_factory=list, description="Candidate target designations/roles")
    summary: Optional[str] = Field(default=None, description="Executive professional summary")


class SalaryInfo(BaseModel):
    """Structured compensation details extracted from job postings."""
    currency: Optional[str] = Field(default=None, description="Currency symbol or code (e.g. $, €, £, USD)")
    min_salary: Optional[float] = Field(default=None, description="Minimum annualized or stated salary")
    max_salary: Optional[float] = Field(default=None, description="Maximum annualized or stated salary")
    period: Optional[str] = Field(default="year", description="Compensation period: year, month, or hour")
    raw_text: Optional[str] = Field(default=None, description="Raw compensation excerpt from job description")


class Job(BaseModel):
    """Job listing model representing a database record."""
    job_id: str = Field(description="Unique identifier for the job")
    title: str = Field(description="Job title/role name")
    company: str = Field(description="Hiring company name")
    location: str = Field(description="Work location (e.g. Remote, Hybrid)")
    experience: str = Field(description="Required experience tier")
    skills: List[str] = Field(default_factory=list, description="Required tech skills")
    description: str = Field(description="Job summary and responsibilities")
    source_link: str = Field(description="Direct URL to original job posting")
    category: Optional[str] = Field(default=None, description="Industry domain or functional category")
    salary: Optional[SalaryInfo] = Field(default=None, description="Extracted salary or compensation information")
    freshness: Optional[str] = Field(default="Recent", description="Job posting recency tier: New, Recent, Archive")
    match_score: Optional[float] = Field(default=None, description="Match score between 0 and 100")
    match_reason: Optional[str] = Field(default=None, description="Personalized reasoning generated by Matcher Agent")


class ApplicationTimelineEvent(BaseModel):
    """Audit event recorded in an application's lifecycle."""
    event_type: str = Field(description="Event type: SUBMITTED, STATUS_CHANGED, NOTES_UPDATED, REMINDER_UPDATED")
    timestamp: str = Field(description="ISO timestamp of the event")
    details: str = Field(description="Human-readable description of event")


class JobApplication(BaseModel):
    """Record of an applied job."""
    job_id: str = Field(description="ID of the job applied to")
    applied_date: str = Field(description="ISO 8601 timestamp of application")
    status: str = Field(default="Applied", description="Current status: Applied, Under Review, Interview, etc.")
    job_title: Optional[str] = Field(default=None, description="Title of the job")
    company: Optional[str] = Field(default=None, description="Company name")
    location: Optional[str] = Field(default=None, description="Job location")
    notes: Optional[str] = Field(default=None, description="Optional applicant cover note or remarks")
    reminder_date: Optional[str] = Field(default=None, description="Optional follow-up reminder date or deadline")
    tags: List[str] = Field(default_factory=list, description="Custom organizational tags/labels")
    timeline: List[ApplicationTimelineEvent] = Field(default_factory=list, description="Audit log of application events")


class ApplicationTagsUpdateRequest(BaseModel):
    """Payload to update custom organization tags on an application."""
    tags: List[str] = Field(..., max_length=15, description="List of custom tags (max 15)")


class ApplicationTimelineResponse(BaseModel):
    """Application event history and timeline response."""
    job_id: str = Field(description="Target job ID")
    total_events: int = Field(description="Total recorded lifecycle events")
    timeline: List[ApplicationTimelineEvent] = Field(default_factory=list, description="Chronological event trail")


class ApplicationReminderUpdateRequest(BaseModel):
    """Payload to set or clear a follow-up reminder on an application."""
    reminder_date: Optional[str] = Field(default=None, description="Follow-up reminder date or timestamp (e.g. '2026-11-20'), or null to clear")


class JobBookmark(BaseModel):
    """Saved / bookmarked job posting record."""
    job_id: str = Field(description="ID of the bookmarked job")
    saved_date: str = Field(description="ISO 8601 timestamp when job was bookmarked")
    job_title: Optional[str] = Field(default=None, description="Title of the job")
    company: Optional[str] = Field(default=None, description="Company name")
    location: Optional[str] = Field(default=None, description="Work location")


class SearchHistoryEntry(BaseModel):
    """Record of a recent candidate job search query."""
    query: Optional[str] = Field(default=None, description="Search keyword or term")
    location: Optional[str] = Field(default=None, description="Location filter")
    experience: Optional[str] = Field(default=None, description="Experience level filter")
    skills: List[str] = Field(default_factory=list, description="Skills filters")
    timestamp: str = Field(description="Timestamp of the search query")
    results_count: int = Field(default=0, description="Number of results matching the search")


class SavedSearchCreateRequest(BaseModel):
    """Payload to create a new saved search subscription / job alert."""
    title: str = Field(..., min_length=1, max_length=100, description="Name/label for the saved search")
    query: Optional[str] = Field(None, description="Search keyword")
    location: Optional[str] = Field(None, description="Location filter")
    experience_level: Optional[str] = Field(None, description="Experience tier filter")
    category: Optional[str] = Field(None, description="Industry domain / category filter")


class SavedSearch(BaseModel):
    """Saved search subscription record."""
    search_id: str = Field(description="Unique identifier for the saved search")
    title: str = Field(description="User-defined title")
    query: Optional[str] = None
    location: Optional[str] = None
    experience_level: Optional[str] = None
    category: Optional[str] = None
    created_date: str = Field(description="Timestamp of creation")


class ChatRequest(BaseModel):
    """Incoming user chat request."""
    message: str = Field(description="User prompt or conversational input")
    session_id: str = Field(default="default-session", description="Session identifier for state tracking")
    profile: Optional[Dict[str, Any]] = Field(default=None, description="Active candidate profile if loaded")


class ChatAction(BaseModel):
    """Structured action or payload returned alongside conversational reply."""
    type: str = Field(description="Action identifier: e.g. JOBS_FOUND, APPLICATION_SUBMITTED, APPLICATIONS_LIST")
    data: Optional[Any] = Field(default=None, description="Structured payload such as job cards or application metadata")


class ChatResponse(BaseModel):
    """Response payload for chat endpoints."""
    reply: str = Field(description="Markdown-formatted conversational response")
    session_id: str = Field(description="Active session ID")
    actions: List[ChatAction] = Field(default_factory=list, description="Optional structured UI widgets/cards")
    profile: Optional[Dict[str, Any]] = Field(default=None, description="Current candidate profile")


class ChatStateResponse(BaseModel):
    """Complete diagnostic and operational state of a chat session."""
    session_id: str
    profile: Optional[Dict[str, Any]] = None
    total_jobs_available: int
    applications: List[JobApplication]
    applied_count: int
    message_count: int
    openai_configured: bool


class UploadResumeResponse(BaseModel):
    """Response payload when a resume file is uploaded and parsed."""
    status: str
    message: str
    profile: ResumeData


class ApplicationCreateRequest(BaseModel):
    """Payload to submit a direct job application."""
    job_id: str = Field(..., min_length=1, description="Unique identifier of the job to apply for")
    notes: Optional[str] = Field(None, max_length=1000, description="Optional applicant notes or cover note")


class ApplicationStatusUpdateRequest(BaseModel):
    """Payload to update an existing job application status."""
    status: str = Field(..., min_length=1, description="Updated status (Applied, Under Review, Interview, Offer, Rejected)")


class BulkApplicationStatusUpdateRequest(BaseModel):
    """Payload for updating status across multiple applications simultaneously."""
    job_ids: List[str] = Field(..., min_length=1, description="List of Job IDs to update")
    status: str = Field(..., min_length=1, description="New status to set (Applied, Under Review, Interview, Offer, Rejected)")


class BulkApplicationStatusUpdateResponse(BaseModel):
    """Response payload for bulk application status updates."""
    updated_count: int = Field(description="Number of applications updated")
    updated_job_ids: List[str] = Field(description="List of Job IDs that were updated")
    status: str = Field(description="New status set")
    message: str = Field(description="Status message")


class ApplicationNotesUpdateRequest(BaseModel):
    """Payload to update personal candidate notes on a submitted job application."""
    notes: str = Field(..., max_length=2000, description="Candidate notes, interview logs, or remarks")


class SkillCount(BaseModel):
    skill: str
    count: int


class LocationCount(BaseModel):
    location: str
    count: int


class JobStatsResponse(BaseModel):
    """Aggregated market statistics across all database job listings."""
    total_jobs: int = Field(description="Total number of jobs in database")
    remote_jobs: int = Field(description="Number of remote job listings")
    top_locations: List[LocationCount] = Field(description="Top hiring locations")
    top_skills: List[SkillCount] = Field(description="Top requested skills")
    experience_breakdown: Dict[str, int] = Field(description="Count of jobs by experience tier")
    category_breakdown: Dict[str, int] = Field(default_factory=dict, description="Count of jobs by industry domain")
    total_applications: int = Field(description="Total submitted applications")


class CompanyCount(BaseModel):
    company: str
    count: int


class ApplicationStatsResponse(BaseModel):
    """Aggregated summary statistics across all submitted job applications."""
    total_applications: int = Field(description="Total number of submitted applications")
    status_breakdown: Dict[str, int] = Field(description="Count of applications by status")
    top_companies: List[CompanyCount] = Field(description="Top companies applied to")
    recent_applications: List[JobApplication] = Field(description="Most recently submitted applications")


class SkillGapAnalysisResponse(BaseModel):
    """Detailed skill comparison and readiness assessment between candidate and job posting."""
    job_id: str = Field(description="Unique identifier of evaluated job")
    job_title: str = Field(description="Job title")
    company: str = Field(description="Company name")
    match_score: float = Field(description="Match relevance score 0-100")
    matching_skills: List[str] = Field(default_factory=list, description="Skills candidate satisfies")
    missing_skills: List[str] = Field(default_factory=list, description="Required skills candidate lacks")
    readiness: str = Field(description="Assessment category: High Readiness, Moderate Readiness, or Needs Preparation")
    recommendation: str = Field(description="Actionable career advice or study recommendations")


class DatabaseBackupSnapshot(BaseModel):
    """Structured snapshot containing full database state across all collections."""
    timestamp: str = Field(description="ISO timestamp when the backup snapshot was generated")
    version: str = Field(default="1.0", description="Backup format schema version")
    applications: List[Dict[str, Any]] = Field(default_factory=list, description="Applications data records")
    bookmarks: List[Dict[str, Any]] = Field(default_factory=list, description="Bookmarks data records")
    saved_searches: List[Dict[str, Any]] = Field(default_factory=list, description="Saved searches data records")
    search_history: List[Dict[str, Any]] = Field(default_factory=list, description="Recent search queries history")


class DatabaseRestoreResponse(BaseModel):
    """Response payload after restoring a database snapshot."""
    status: str = Field(description="Operation result status: success or error")
    message: str = Field(description="Human-readable result summary")
    restored_counts: Dict[str, int] = Field(description="Count of restored records per collection")


class CollectionHealthStatus(BaseModel):
    """Health and integrity metrics for a single JSON database collection."""
    collection: str = Field(description="Collection name identifier")
    exists: bool = Field(description="Whether collection file exists on disk")
    record_count: int = Field(description="Number of parsed JSON objects")
    file_size_bytes: int = Field(description="Storage size in bytes")
    status: str = Field(description="Health status: healthy, missing, or corrupted")
    last_modified: Optional[str] = Field(None, description="ISO timestamp of last modification")


class DatabaseHealthResponse(BaseModel):
    """Diagnostic health report across all local JSON collections."""
    status: str = Field(description="Overall database health: healthy, degraded, or unhealthy")
    total_collections: int = Field(description="Total monitored collections count")
    healthy_collections: int = Field(description="Number of collections in healthy state")
    collections: List[CollectionHealthStatus] = Field(default_factory=list, description="Collection health statuses")
