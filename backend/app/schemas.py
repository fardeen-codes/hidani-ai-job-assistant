"""
Pydantic Schemas for Hidani AI Job Assistant.
Defines data structures for resumes, jobs, applications, and chat interactions.
"""

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class ResumeData(BaseModel):
    """Structured representation of extracted candidate resume data matching assessment criteria."""
    name: str = Field(default="Candidate", description="Applicant full name")
    contact: str = Field(default="", description="Email and phone contact information")
    email: Optional[str] = Field(default=None, description="Contact email address")
    phone: Optional[str] = Field(default=None, description="Contact phone number")
    designation: str = Field(default="Software Engineer", description="Current or target professional designation/title")
    skills: List[str] = Field(default_factory=list, description="Technical and domain skills")
    experience: str = Field(default="1-3 years", description="Total experience and background summary")
    experience_years: Optional[str] = Field(default="1-3 years", description="Years of total experience")
    experience_level: Optional[str] = Field(default="Mid-Level", description="Entry-Level, Mid-Level, Senior, or Lead")
    education: List[str] = Field(default_factory=list, description="Academic degrees, university, graduation year")
    projects: List[str] = Field(default_factory=list, description="Key projects worked on with brief tech stack")
    preferred_roles: List[str] = Field(default_factory=list, description="Candidate target designations/roles")
    summary: Optional[str] = Field(default=None, description="Executive professional summary")


class Job(BaseModel):
    """Job listing model representing a database record."""
    job_id: str = Field(description="Unique identifier for the job")
    title: str = Field(description="Job title/role name")
    company: str = Field(description="Hiring company name")
    location: str = Field(description="Work location (e.g. Remote, Hybrid)")
    experience: str = Field(description="Required experience tier")
    skills: List[str] = Field(default_factory=list, description="Required tech skills")
    description: str = Field(description="Job summary and responsibilities")
    source_link: str = Field(description="Direct URL to original job posting")
    match_score: Optional[float] = Field(default=None, description="Match score between 0 and 100")
    match_reason: Optional[str] = Field(default=None, description="Personalized reasoning generated by Matcher Agent")


class JobApplication(BaseModel):
    """Record of an applied job."""
    job_id: str = Field(description="ID of the job applied to")
    applied_date: str = Field(description="ISO 8601 timestamp of application")
    status: str = Field(default="Applied", description="Current status: Applied, Under Review, Interview, etc.")
    job_title: Optional[str] = Field(default=None, description="Title of the job")
    company: Optional[str] = Field(default=None, description="Company name")
    location: Optional[str] = Field(default=None, description="Job location")
    notes: Optional[str] = Field(default=None, description="Optional applicant cover note or remarks")


class JobBookmark(BaseModel):
    """Saved / bookmarked job posting record."""
    job_id: str = Field(description="ID of the bookmarked job")
    saved_date: str = Field(description="ISO 8601 timestamp when job was bookmarked")
    job_title: Optional[str] = Field(default=None, description="Title of the job")
    company: Optional[str] = Field(default=None, description="Company name")
    location: Optional[str] = Field(default=None, description="Work location")


class ChatRequest(BaseModel):
    """Incoming user chat request."""
    message: str = Field(description="User prompt or conversational input")
    session_id: str = Field(default="default-session", description="Session identifier for state tracking")
    profile: Optional[Dict[str, Any]] = Field(default=None, description="Active candidate profile if loaded")


class ChatAction(BaseModel):
    """Structured action or payload returned alongside conversational reply."""
    type: str = Field(description="Action identifier: e.g. JOBS_FOUND, APPLICATION_SUBMITTED, APPLICATIONS_LIST")
    data: Optional[Any] = Field(default=None, description="Structured payload such as job cards or application metadata")


class ChatResponse(BaseModel):
    """Response payload for chat endpoints."""
    reply: str = Field(description="Markdown-formatted conversational response")
    session_id: str = Field(description="Active session ID")
    actions: List[ChatAction] = Field(default_factory=list, description="Optional structured UI widgets/cards")
    profile: Optional[Dict[str, Any]] = Field(default=None, description="Current candidate profile")


class ChatStateResponse(BaseModel):
    """Complete diagnostic and operational state of a chat session."""
    session_id: str
    profile: Optional[Dict[str, Any]] = None
    total_jobs_available: int
    applications: List[JobApplication]
    applied_count: int
    message_count: int
    openai_configured: bool


class UploadResumeResponse(BaseModel):
    """Response payload when a resume file is uploaded and parsed."""
    status: str
    message: str
    profile: ResumeData


class ApplicationCreateRequest(BaseModel):
    """Payload to submit a direct job application."""
    job_id: str = Field(..., min_length=1, description="Unique identifier of the job to apply for")
    notes: Optional[str] = Field(None, max_length=1000, description="Optional applicant notes or cover note")


class ApplicationStatusUpdateRequest(BaseModel):
    """Payload to update an existing job application status."""
    status: str = Field(..., min_length=1, description="Updated status (Applied, Under Review, Interview, Offer, Rejected)")


class SkillCount(BaseModel):
    skill: str
    count: int


class LocationCount(BaseModel):
    location: str
    count: int


class JobStatsResponse(BaseModel):
    """Aggregated market statistics across all database job listings."""
    total_jobs: int = Field(description="Total number of jobs in database")
    remote_jobs: int = Field(description="Number of remote job listings")
    top_locations: List[LocationCount] = Field(description="Top hiring locations")
    top_skills: List[SkillCount] = Field(description="Top requested skills")
    experience_breakdown: Dict[str, int] = Field(description="Count of jobs by experience tier")
    total_applications: int = Field(description="Total submitted applications")


class CompanyCount(BaseModel):
    company: str
    count: int


class ApplicationStatsResponse(BaseModel):
    """Aggregated summary statistics across all submitted job applications."""
    total_applications: int = Field(description="Total number of submitted applications")
    status_breakdown: Dict[str, int] = Field(description="Count of applications by status")
    top_companies: List[CompanyCount] = Field(description="Top companies applied to")
    recent_applications: List[JobApplication] = Field(description="Most recently submitted applications")
