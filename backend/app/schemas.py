class JobApplication(BaseModel):
    """Record of an applied job."""
    job_id: str = Field(description="ID of the job applied to")
    applied_date: str = Field(description="ISO 8601 timestamp of application")
    status: str = Field(default="Applied", description="Current status: Applied, Under Review, Interview, etc.")
    job_title: Optional[str] = Field(default=None, description="Title of the job")
    company: Optional[str] = Field(default=None, description="Company name")
    location: Optional[str] = Field(default=None, description="Job location")
    notes: Optional[str] = Field(default=None, description="Optional applicant cover note or remarks")
    reminder_date: Optional[str] = Field(default=None, description="Optional follow-up reminder date or deadline")
    tags: List[str] = Field(default_factory=list, description="Custom organizational tags/labels")
    interviews: List[InterviewStageEntry] = Field(default_factory=list, description="Logged interview rounds")
    attachments: List[ApplicationAttachment] = Field(default_factory=list, description="Associated document attachments")
    is_archived: bool = Field(default=False, description="Whether application has been archived")
    archived_date: Optional[str] = Field(default=None, description="Timestamp of archiving")
    priority: Optional[str] = Field(default="Medium", description="Application priority level: Low, Medium, High, Urgent")
    is_favorite: Optional[bool] = Field(default=False, description="Candidate starred / favorited flag")
    decision_deadline: Optional[str] = Field(default=None, description="Candidate target offer or decision deadline")
    expected_feedback_date: Optional[str] = Field(default=None, description="Expected feedback or response date from company")
    outcome: Optional[str] = Field(default=None, description="Final outcome: Offer, Rejected, Accepted, Declined")
    rejection_reason: Optional[str] = Field(default=None, description="Reason code: Skill Gap, Compensation, Headcount, etc.")
    feedback_notes: Optional[str] = Field(default=None, description="Detailed interviewer or debrief feedback")
    source: Optional[str] = Field(default="Direct / Portal", description="Application submission channel")
    interview_questions: List[Dict[str, Any]] = Field(default_factory=list, description="Logged interview preparation questions")
    timeline: List[ApplicationTimelineEvent] = Field(default_factory=list, description="Audit log of application events")


